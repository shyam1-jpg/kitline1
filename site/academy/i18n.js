window.kaT = function (key) {
  const lang = window.kaLang || 'en';
  const pack = window.KA_I18N[lang] || window.KA_I18N.en;
  return pack[key] || window.KA_I18N.en[key] || key;
};

window.applyKaLang = function (lang) {
  if (!window.KA_I18N[lang]) lang = 'en';
  window.kaLang = lang;
  localStorage.setItem('kit_lang', lang);
  const meta = window.KA_LANGS[lang] || window.KA_LANGS.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = meta.dir || 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const k = el.getAttribute('data-i18n');
    const val = window.kaT(k);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = val;
    else el.textContent = val;
  });
  if (typeof window.onKaLangChange === 'function') window.onKaLangChange();
};

window.kaLang = localStorage.getItem('kit_lang') || (navigator.language || 'en').slice(0, 2);
if (!window.KA_I18N[window.kaLang]) window.kaLang = 'en';
